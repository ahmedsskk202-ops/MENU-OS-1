/** Label for a raw enum value (order status, payment method...). Unknown values fall back
 *  to a readable form of the value itself rather than the missing-key string. */
export function enumLabel(t: (key: string) => string, value: string) {
  const key = `admin.enum.${value}`;
  const s = t(key);
  return s === key ? value.replace(/_/g, " ") : s;
}
